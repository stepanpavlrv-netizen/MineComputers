    private PixelFont() {
    }

    static Glyph glyph(char c) {
        Glyph gl = GLYPHS.get(c);
        if (gl == null) gl = GLYPHS.get(Character.toUpperCase(c));
        return gl == null ? UNKNOWN : gl;
    }

    /** Ширина строки в точках (при масштабе 1, без последнего промежутка). */
    public static int width(String text) {
        int w = 0;
        for (int i = 0; i < text.length(); i++) w += glyph(text.charAt(i)).w() + (i > 0 ? 1 : 0);
        return w;
    }

    /**
     * Нарисовать строку в буфер px (ширина bw, высота bh) с точки (x, y), масштаб scale (целый), цвет rgb.
     * outline ≥ 0 — цвет обводки в одну точку масштаба вокруг букв (читается на любом фоне). Возвращает ширину.
     */
    public static int draw(int[] px, int bw, int bh, int x, int y, String text, int rgb, int scale, int outline) {
        scale = Math.max(1, Math.min(16, scale));
        if (outline >= 0) {
            for (int oy = -1; oy <= 1; oy++)
                for (int ox = -1; ox <= 1; ox++)
                    if (ox != 0 || oy != 0) put(px, bw, bh, x + ox * scale, y + oy * scale, text, outline, scale);
        }
        return put(px, bw, bh, x, y, text, rgb, scale);
    }

    private static int put(int[] px, int bw, int bh, int x, int y, String text, int rgb, int scale) {
        int cx = x;
        for (int i = 0; i < text.length(); i++) {
            Glyph gl = glyph(text.charAt(i));
            for (int ry = 0; ry < HEIGHT; ry++) {
                int bits = gl.rows()[ry];
                if (bits == 0) continue;
                for (int rx = 0; rx < gl.w(); rx++) {
                    if ((bits >> rx & 1) == 0) continue;
                    int x0 = cx + rx * scale, y0 = y + ry * scale;
                    for (int sy = 0; sy < scale; sy++) {
                        int yy = y0 + sy;
                        if (yy < 0 || yy >= bh) continue;
                        int row = yy * bw;
                        for (int sx = 0; sx < scale; sx++) {
                            int xx = x0 + sx;
                            if (xx >= 0 && xx < bw) px[row + xx] = rgb;
                        }
                    }
                }
            }
            cx += (gl.w() + 1) * scale;
        }
        return Math.max(0, cx - x - scale);
    }
