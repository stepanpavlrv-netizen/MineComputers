    public static final int HEIGHT = 7;

    /** Буква: ширина и строки (бит 0 — левая точка). */
    record Glyph(int w, int[] rows) {
    }

    private static final Map<Character, Glyph> GLYPHS = new HashMap<>();
    private static final Glyph UNKNOWN;

    private static void g(String chars, String... rows) {
        if (rows.length != HEIGHT) throw new IllegalStateException("буква " + chars + ": строк " + rows.length);
        int w = rows[0].length();
        int[] bits = new int[HEIGHT];
        for (int y = 0; y < HEIGHT; y++) {
            if (rows[y].length() != w) throw new IllegalStateException("буква " + chars + ": строка " + y);
            for (int x = 0; x < w; x++) if (rows[y].charAt(x) == '#') bits[y] |= 1 << x;
        }
        Glyph gl = new Glyph(w, bits);
        for (char c : chars.toCharArray()) GLYPHS.put(c, gl);
    }

